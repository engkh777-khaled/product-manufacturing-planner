-- M04 · Planning runs, schedule versions, production orders/operations, alerts, approvals, audit (spec §6.16–6.22).

create table public.planning_runs (
  id                     uuid primary key default gen_random_uuid(),
  run_number             bigint generated by default as identity (start with 1100) unique,
  run_type               text not null check (run_type in ('mrp', 'schedule', 'simulation')),
  planning_horizon_start date not null,
  planning_horizon_end   date not null,
  input_snapshot         jsonb not null default '{}'::jsonb,
  scenario_assumptions   jsonb not null default '{}'::jsonb,
  algorithm_version      text not null,
  solver_status          text not null default 'Pending' check (solver_status in (
                           'Pending', 'Running', 'Feasible', 'Feasible with lateness', 'Needs data',
                           'Infeasible', 'Solver limit reached', 'Failed')),
  objective_value        numeric,
  solve_seconds          numeric(10, 3) check (solve_seconds >= 0),
  started_at             timestamptz,
  completed_at           timestamptz,
  created_by             uuid references auth.users (id) on delete set null,
  created_at             timestamptz not null default now(),
  constraint planning_runs_horizon check (planning_horizon_end >= planning_horizon_start),
  constraint planning_runs_timing check (completed_at is null or started_at is null or completed_at >= started_at)
);
create index planning_runs_created_by_idx on public.planning_runs (created_by);
comment on column public.planning_runs.solver_status is
  'Spec §8.7 outcomes. Never report Infeasible when the solver only hit its time limit.';

create table public.schedule_versions (
  id                  uuid primary key default gen_random_uuid(),
  planning_run_id     uuid not null references public.planning_runs (id) on delete restrict,
  version_number      text not null unique,
  label               text,
  status              text not null default 'Draft'
                      check (status in ('Draft', 'Proposed', 'Approved', 'Rejected', 'Superseded')),
  is_baseline         boolean not null default false,
  based_on_version_id uuid references public.schedule_versions (id) on delete set null,
  change_summary      text,
  metrics             jsonb not null default '{}'::jsonb,
  validation_passed   boolean,
  created_by          uuid references auth.users (id) on delete set null,
  created_at          timestamptz not null default now(),
  approved_by         uuid references auth.users (id) on delete set null,
  approved_at         timestamptz,
  constraint schedule_versions_baseline_is_approved check (not is_baseline or status = 'Approved'),
  constraint schedule_versions_approval_stamped check (status not in ('Approved', 'Superseded') or approved_at is not null),
  constraint schedule_versions_no_unvalidated_approval check (status <> 'Approved' or validation_passed)
);
-- Exactly one approved baseline at a time; scenarios never overwrite it (spec §6.19, §10).
create unique index schedule_versions_single_baseline on public.schedule_versions (is_baseline) where is_baseline;
create index schedule_versions_planning_run_id_idx on public.schedule_versions (planning_run_id);
create index schedule_versions_based_on_idx on public.schedule_versions (based_on_version_id);
create index schedule_versions_created_by_idx on public.schedule_versions (created_by);
create index schedule_versions_approved_by_idx on public.schedule_versions (approved_by);
comment on column public.schedule_versions.metrics is 'late_orders, total_lateness_hours, overtime_cost, hard_violations, soft_violations.';

create table public.production_orders (
  id                      uuid primary key default gen_random_uuid(),
  production_order_number text not null,
  schedule_version_id     uuid not null references public.schedule_versions (id) on delete cascade,
  sales_order_item_id     uuid references public.sales_order_items (id) on delete restrict,
  product_id              uuid not null references public.products (id) on delete restrict,
  quantity                numeric(14, 4) not null check (quantity > 0),
  status                  text not null default 'Planned'
                          check (status in ('Planned', 'Released', 'In Progress', 'Completed', 'Cancelled')),
  planned_start           timestamptz,
  planned_finish          timestamptz,
  actual_start            timestamptz,
  actual_finish           timestamptz,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  constraint production_orders_number_per_version unique (schedule_version_id, production_order_number),
  constraint production_orders_planned_range check (planned_finish is null or planned_start is null or planned_finish >= planned_start),
  constraint production_orders_actual_range check (actual_finish is null or actual_start is null or actual_finish >= actual_start)
);
create index production_orders_sales_order_item_id_idx on public.production_orders (sales_order_item_id);
create index production_orders_product_id_idx on public.production_orders (product_id);
comment on table public.production_orders is 'One set per schedule version, so scenarios never touch the baseline.';

create table public.production_operations (
  id                   uuid primary key default gen_random_uuid(),
  production_order_id  uuid not null references public.production_orders (id) on delete cascade,
  routing_operation_id uuid not null references public.routing_operations (id) on delete restrict,
  operation_number     text not null,
  quantity             numeric(14, 4) not null check (quantity > 0),
  status               text not null default 'Planned'
                       check (status in ('Planned', 'Released', 'In Progress', 'Completed', 'Cancelled')),
  planned_start        timestamptz,
  planned_finish       timestamptz,
  actual_start         timestamptz,
  actual_finish        timestamptz,
  assigned_machine_id  uuid references public.machines (id) on delete restrict,
  is_frozen            boolean not null default false,
  notes                text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint production_operations_number_key unique (production_order_id, operation_number),
  constraint production_operations_planned_range check (planned_finish is null or planned_start is null or planned_finish >= planned_start),
  constraint production_operations_actual_range check (actual_finish is null or actual_start is null or actual_finish >= actual_start),
  constraint production_operations_completed_has_actuals check (status <> 'Completed' or actual_finish is not null)
);
create index production_operations_routing_operation_id_idx on public.production_operations (routing_operation_id);
create index production_operations_machine_start_idx on public.production_operations (assigned_machine_id, planned_start);

create table public.planning_alerts (
  id                  uuid primary key default gen_random_uuid(),
  planning_run_id     uuid references public.planning_runs (id) on delete cascade,
  sales_order_item_id uuid references public.sales_order_items (id) on delete cascade,
  production_order_id uuid references public.production_orders (id) on delete cascade,
  alert_type          text not null check (alert_type in (
                        'material_shortage', 'late_supplier_receipt', 'quality_hold', 'capacity_overload',
                        'missing_bom', 'missing_routing', 'delivery_date_at_risk',
                        'machine_downtime_conflict', 'infeasible_schedule')),
  severity            text not null check (severity in ('critical', 'warning', 'info')),
  description         text not null,
  recommended_action  text,
  details             jsonb not null default '{}'::jsonb,
  status              text not null default 'Open' check (status in ('Open', 'Acknowledged', 'Resolved', 'Dismissed')),
  created_at          timestamptz not null default now()
);
create index planning_alerts_planning_run_id_idx on public.planning_alerts (planning_run_id);
create index planning_alerts_sales_order_item_id_idx on public.planning_alerts (sales_order_item_id);
create index planning_alerts_production_order_id_idx on public.planning_alerts (production_order_id);

create table public.approval_requests (
  id                  uuid primary key default gen_random_uuid(),
  request_number      text not null unique,
  schedule_version_id uuid not null references public.schedule_versions (id) on delete cascade,
  requested_by        uuid references auth.users (id) on delete set null,
  approver_id         uuid references auth.users (id) on delete set null,
  status              text not null default 'Pending'
                      check (status in ('Pending', 'Approved', 'Rejected', 'Withdrawn')),
  comments            text,
  requested_at        timestamptz not null default now(),
  decided_at          timestamptz,
  constraint approval_requests_decision_stamped check ((status in ('Approved', 'Rejected')) = (decided_at is not null))
);
create unique index approval_requests_one_pending_per_version on public.approval_requests (schedule_version_id) where status = 'Pending';
create index approval_requests_requested_by_idx on public.approval_requests (requested_by);
create index approval_requests_approver_id_idx on public.approval_requests (approver_id);

create table public.audit_logs (
  id          bigint generated always as identity primary key,
  user_id     uuid references auth.users (id) on delete set null,
  action      text not null,
  entity_type text not null,
  entity_id   uuid,
  before_data jsonb,
  after_data  jsonb,
  reason      text,
  created_at  timestamptz not null default now()
);
create index audit_logs_entity_idx on public.audit_logs (entity_type, entity_id);
create index audit_logs_user_id_idx on public.audit_logs (user_id);
create index audit_logs_created_at_idx on public.audit_logs (created_at desc);
comment on table public.audit_logs is 'Append-only record of consequential changes. Triggers and immutability arrive in M07.';

create trigger production_orders_set_updated_at before update on public.production_orders
  for each row execute function public.set_updated_at();
create trigger production_operations_set_updated_at before update on public.production_operations
  for each row execute function public.set_updated_at();

